def context_length_for_sign_in(sign_in_present: Optional[bool]) -> int:
    if sign_in_present is False:
        return SIGNED_IN_INPUT_CONTEXT_LENGTH
    return SIGNED_OUT_INPUT_CONTEXT_LENGTH

