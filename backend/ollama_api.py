@router.post("/api/show")
async def show_model(req: dict):
    model = req.get("model")
    sign_in_present = await bridge.request_gemini_sign_in_presence()
    input_context_length = context_length_for_sign_in(sign_in_present)
    entry = get_model_entry(input_context_length)
    if model != entry["model"] and model != entry["name"]:
        raise HTTPException(status_code=404, detail="model not found")
        
    return {
        "modelfile": f"# Modelfile generated by gemini-proxy\nFROM {entry['model']}\n",
        "parameters": f"num_ctx {input_context_length}\nnum_predict {OUTPUT_CONTEXT_LENGTH}\n",
        "template": "{{ .Prompt }}",
        "details": entry["details"],
        "capabilities": ["completion", "chat", "vision", "tools", "thinking"],
        "model_info": get_model_info(input_context_length)
    }

