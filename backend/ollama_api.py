# Ollama Generate & Chat
def validate_generate_request(req: dict):
    if "suffix" in req:
        raise HTTPException(status_code=400, detail="the `suffix` field is not supported")
    if "format" in req:
        fmt = req["format"]
        if fmt != "json":
            raise HTTPException(status_code=400, detail="the `format` field only supports the string `json`")
    if "raw" in req:
        raise HTTPException(status_code=400, detail="the `raw` field is not supported")
    if "logprobs" in req or "top_logprobs" in req:
        raise HTTPException(status_code=400, detail="the `logprobs` and `top_logprobs` fields are not supported")

def format_prompt(system: Optional[str], prompt: str) -> str:
    if not prompt.strip():
        return prompt
    if not system or not system.strip():
        return prompt
    messages = [
        {"role": "system", "content": system},
        {"role": "user", "content": prompt}
    ]
    return json.dumps(messages)

@router.post("/api/generate")
async def generate(req: dict):
    validate_generate_request(req)
    model = req.get("model", "gemini-proxy")
    prompt = format_prompt(req.get("system"), req.get("prompt", ""))
    images = req.get("images") or []
    files = [decode_image_to_file(img) for img in images]
    stream_enabled = req.get("stream", True)
    created_at = "2026-03-13T00:00:00.000000000Z"
    
    if not bridge.active_websocket:
        raise HTTPException(status_code=503, detail="No browser extension connected")
        
    if not model.startswith("gemini") and model != "gemini-proxy":
        if stream_enabled:
            async def unsupported_stream():
                yield json.dumps({
                    "model": model,
                    "created_at": created_at,
                    "response": "Unsupported model",
                    "done": True
                }) + "\n"
            return StreamingResponse(unsupported_stream(), media_type="application/x-ndjson")
        else:
            return {
                "model": model,
                "created_at": created_at,
                "response": "Unsupported model",
                "done": True,
                "done_reason": "stop",
                "total_duration": 0,
                "load_duration": 0,
                "prompt_eval_count": 0,
                "prompt_eval_duration": 0,
                "eval_count": 0,
                "eval_duration": 0,
            }
            
    cmd_id = await bridge.get_next_id()
    queue = asyncio.Queue()
    bridge.register_receiver(cmd_id, queue)
    
    try:
        await bridge.send_command(cmd_id, "gemini-generate", prompt=prompt, files=files)
    except Exception as e:
        bridge.unregister_receiver(cmd_id)
        raise HTTPException(status_code=500, detail=f"Failed to send command: {e}")
        
    if stream_enabled:
        async def ollama_generate_stream():
            try:
                while True:
                    try:
                        item = await asyncio.wait_for(queue.get(), timeout=1200.0)
                    except asyncio.TimeoutError:
                        yield json.dumps({
                            "model": model,
                            "created_at": created_at,
                            "response": "",
                            "done": True,
                            "error": "Timeout waiting for response from browser extension"
                        }) + "\n"
                        break
                        
                    error = item.get("error")
                    if error:
                        yield json.dumps({
                            "model": model,
                            "created_at": created_at,
                            "response": "",
                            "done": True,
                            "error": error
                        }) + "\n"
                        break
                        
                    text = item.get("text", "")
                    done = item.get("done", False)
                    
                    yield json.dumps({
                        "model": model,
                        "created_at": created_at,
                        "response": text,
                        "done": done
                    }) + "\n"
                    
                    if done:
                        break
            finally:
                bridge.unregister_receiver(cmd_id)
        return StreamingResponse(ollama_generate_stream(), media_type="application/x-ndjson")
    else:
        accumulated_text = []
        try:
            while True:
                try:
                    item = await asyncio.wait_for(queue.get(), timeout=1200.0)
                except asyncio.TimeoutError:
                    raise HTTPException(status_code=504, detail="Timeout waiting for browser response")
                error = item.get("error")
                if error:
                    raise HTTPException(status_code=500, detail=error)
                text = item.get("text", "")
                if text:
                    accumulated_text.append(text)
                if item.get("done", False):
                    break
        finally:
            bridge.unregister_receiver(cmd_id)
            
        full_text = "".join(accumulated_text)
        return {
            "model": model,
            "created_at": created_at,
            "response": full_text,
            "done": True,
            "done_reason": "stop",
            "total_duration": 0,
            "load_duration": 0,
            "prompt_eval_count": 0,
            "prompt_eval_duration": 0,
            "eval_count": 0,
            "eval_duration": 0,
        }

