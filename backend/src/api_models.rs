#[derive(Debug, Clone, Serialize)]
pub struct TagsResponse {
    models: Vec<ModelEntry>,
}

#[derive(Debug, Clone, Serialize)]
pub struct ModelEntry {
    name: String,
    model: String,
    modified_at: String,
    size: u64,
    digest: String,
    details: ModelDetails,
}

#[derive(Debug, Clone, Serialize)]
pub struct ModelDetails {
    format: String,
    family: String,
    families: Vec<String>,
    parameter_size: String,
    quantization_level: String,
}

#[derive(Debug, Clone, Serialize)]
pub struct PsResponse {
    models: Vec<RunningModelEntry>,
}

#[derive(Debug, Clone, Serialize)]
pub struct RunningModelEntry {
    name: String,
    model: String,
    size: u64,
    digest: String,
    details: RunningModelDetails,
    expires_at: String,
    size_vram: u64,
}

#[derive(Debug, Clone, Serialize)]
pub struct RunningModelDetails {
    parent_model: String,
    format: String,
    family: String,
    families: Vec<String>,
    parameter_size: String,
    quantization_level: String,
}

#[derive(Debug, Deserialize)]
pub struct ShowRequest {
    model: String,
    #[serde(default)]
    verbose: Option<bool>,
}

#[derive(Debug, Serialize)]
pub struct ShowResponse {
    modelfile: String,
    parameters: String,
    template: String,
    details: ModelDetails,
    model_info: Value,
}

#[derive(Debug, Clone)]
struct ModelCatalogEntry {
    tag: ModelEntry,
    modelfile: String,
    parameters: String,
    template: String,
    model_info: Value,
}

impl ModelCatalogEntry {
    fn to_running_model(&self) -> RunningModelEntry {
        RunningModelEntry {
            name: self.tag.name.clone(),
            model: self.tag.model.clone(),
            size: self.tag.size,
            digest: self.tag.digest.clone(),
            details: RunningModelDetails {
                parent_model: "".to_string(),
                format: self.tag.details.format.clone(),
                family: self.tag.details.family.clone(),
                families: self.tag.details.families.clone(),
                parameter_size: self.tag.details.parameter_size.clone(),
                quantization_level: self.tag.details.quantization_level.clone(),
            },
            expires_at: "2099-12-31T23:59:59Z".to_string(),
            size_vram: self.tag.size,
        }
    }
}

