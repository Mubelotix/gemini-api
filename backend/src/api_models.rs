#[get("/api/tags")]
pub async fn tags(state: &State<ExtensionBridge>) -> Json<TagsResponse> {
    let sign_in_present = request_gemini_sign_in_presence(state).await.ok();
    let gemini_available = matches!(sign_in_present, Some(false));

    let mut models = Vec::new();
    if gemini_available {
        models.push(gemini_catalog_entry().tag);
    }

    Json(TagsResponse { models })
}

#[get("/api/ps")]
pub async fn running_models(state: &State<ExtensionBridge>) -> Json<PsResponse> {
    let sign_in_present = request_gemini_sign_in_presence(state).await.ok();
    let gemini_available = matches!(sign_in_present, Some(false));

    let mut models = Vec::new();
    if gemini_available {
        models.push(gemini_catalog_entry().to_running_model());
    }

    Json(PsResponse { models })
}

#[post("/api/show", format = "json", data = "<payload>")]
pub async fn show_model(payload: Json<ShowRequest>) -> AppResult<Json<ShowResponse>> {
    let req = payload.into_inner();
    let _verbose = req.verbose.unwrap_or(false);

    let entry = gemini_catalog_entry();
    if req.model != entry.tag.model && req.model != entry.tag.name {
        bail!("model not found");
    }

    Ok(Json(ShowResponse {
        modelfile: entry.modelfile,
        parameters: entry.parameters,
        template: entry.template,
        details: entry.tag.details,
        model_info: entry.model_info,
    }))
}
